# Find (and optionally remove) unnecessary parents in taxonomy files.
#
# A parent of an entry is unnecessary when it is already an ancestor of another parent of the same entry:
#
# < en: Canned foods     <- unnecessary, Canned seafood is already a child of Canned foods
# < en: Canned seafood
# en: Canned shrimps
#
# A parent line that resolves to the same entry as a previous parent line of the entry is also unnecessary.

use ProductOpener::PerlStandards;

use Encode qw/decode/;
use Getopt::Long qw/GetOptions/;

use ProductOpener::Store qw/get_string_id_for_lang/;
use ProductOpener::Tags qw/%stopwords get_lc_tagid remove_plurals remove_stopwords sanitize_taxonomy_line/;

# each call to load_taxonomy() uses its own key in %stopwords (stopwords regexps are cached by tagtype)
my $loaded_taxonomies_count = 0;

=head2 load_taxonomy (\@files)

Load one or more taxonomy files as a single taxonomy (like the build does when it concatenates
several files, e.g. additives and ingredients) and compute direct parents of each entry.

Parent names are resolved to the canonical entry the same way the build does:
a parent can be written with any synonym of the entry, in any language, with or without stopwords and plurals.
Synonyms generated by the build by substituting synonyms inside other synonyms are not computed:
parents that use them are listed in unknown_parents.
Names in xx: (language-less) entries are also used as a fallback for every language.

Returns a hash ref with:
- entries: list of entries, each with file, start_line, canon_id, name (first line) and parents
  (list of parent lines with line_num, line, canon_id, which is undef if the parent was not found)
- direct_parents: canon_id -> parent canon_id -> 1
- unknown_parents: list of parents that could not be resolved

=cut

sub load_taxonomy ($files_ref) {

	my $tagtype = "redundant_parents_" . (++$loaded_taxonomies_count);
	$stopwords{$tagtype} = {};

	my %synonyms = ();    # lc -> tagid -> lc_tagid
	my %translations_from = ();    # lc:lc_tagid -> canon_id
	my @entries = ();
	my %lines = ();    # file -> list of raw lines (bytes)

	# first pass: entries, synonyms and stopwords
	foreach my $file (@$files_ref) {
		open(my $in, "<:raw", $file) or die("Cannot open $file: $!\n");
		my @raw_lines = <$in>;
		close($in);
		$lines{$file} = \@raw_lines;

		my $entry;
		my $line_num = 0;
		foreach my $raw_line (@raw_lines, "\n") {
			$line_num++;
			my $line = sanitize_taxonomy_line(decode("UTF-8", $raw_line));

			if ($line =~ /^\s*$/) {
				# end of block
				push @entries, $entry if ((defined $entry) and (defined $entry->{canon_id}));
				$entry = undef;
				next;
			}
			next if $line =~ /^#/;

			$entry //= {file => $file, start_line => $line_num, parents => []};

			if ($line =~ /^stopwords:(\w\w):\s*(.*)/) {
				my $lc = $1;
				foreach my $stopword (split(/\s*,\s*/, $2)) {
					my $tagid = get_string_id_for_lang($lc, $stopword);
					push @{$stopwords{$tagtype}{$lc}}, $tagid if $tagid ne '';
				}
			}
			elsif ($line =~ /^<\s*(\w\w):(.*)/) {
				push @{$entry->{parents}}, {line_num => $line_num, line => $line, lc => $1, name => $2};
			}
			elsif ($line =~ /^(synonyms:)?(\w\w):(.*)/) {
				my $is_synonyms = $1;
				my $lc = $2;
				my @tags = split(/\s*,\s*/, $3 =~ s/^\s+//r);
				next if not @tags;
				my $lc_tagid = get_string_id_for_lang($lc, $tags[0]);
				if (not defined $entry->{canon_id}) {
					# an entry with the same canonical id already exists: we merge the two
					$entry->{canon_id} = $translations_from{"$lc:$lc_tagid"} // "$lc:$lc_tagid";
					$entry->{name} = $line;
					$entry->{is_synonyms} = 1 if $is_synonyms;
				}
				$translations_from{"$lc:$lc_tagid"} //= $entry->{canon_id};
				foreach my $tag (@tags) {
					my $tagid = get_string_id_for_lang($lc, $tag);
					next if $tagid eq '';
					$synonyms{$lc}{$tagid} //= $lc_tagid;
				}
			}
		}
	}

	# add synonyms without stopwords and plurals, like the build does
	foreach my $lc (sort keys %synonyms) {
		foreach my $tagid (sort keys %{$synonyms{$lc}}) {
			my $tagid2 = $tagid;
			$tagid2 = remove_stopwords($tagtype, $lc, $tagid2) if $tagid2 =~ /-.+-/;
			$tagid2 = remove_plurals($lc, $tagid2);
			next if $tagid2 eq "";
			$synonyms{$lc}{$tagid2} //= $synonyms{$lc}{$tagid};
		}
	}

	# second pass: resolve parents
	my %direct_parents = ();
	my @unknown_parents = ();
	foreach my $entry (@entries) {
		foreach my $parent (@{$entry->{parents}}) {
			# the build considers parenthesis as spaces for parents
			my $name = $parent->{name} =~ s/\(|\)/-/gr;
			foreach my $lc ($parent->{lc}, "xx") {
				my $lc_tagid = get_lc_tagid(\%synonyms, $lc, $tagtype, $name, "");
				next if not defined $lc_tagid;
				$parent->{canon_id} = $translations_from{"$lc:$lc_tagid"};
				last;
			}
			if (defined $parent->{canon_id}) {
				$direct_parents{$entry->{canon_id}}{$parent->{canon_id}} = 1
					if $parent->{canon_id} ne $entry->{canon_id};
			}
			else {
				push @unknown_parents, {%$parent, file => $entry->{file}, entry => $entry->{canon_id}};
			}
		}
	}

	delete $stopwords{$tagtype};

	return {
		entries => \@entries,
		direct_parents => \%direct_parents,
		unknown_parents => \@unknown_parents,
		lines => \%lines,
	};
}

=head2 find_path ($direct_parents_ref, $from, $to)

Return a list of canonical ids going from $from to its ancestor $to, through direct parents
(shortest path), or undef if $to is not an ancestor of $from. Cycles are handled.

=cut

sub find_path ($direct_parents_ref, $from, $to) {
	my %previous = ($from => undef);
	my @queue = ($from);
	while (@queue) {
		my $id = shift @queue;
		foreach my $parent_id (sort keys %{$direct_parents_ref->{$id} // {}}) {
			next if exists $previous{$parent_id};
			$previous{$parent_id} = $id;
			if ($parent_id eq $to) {
				my @path = ($to);
				while (defined $previous{$path[0]}) {
					unshift @path, $previous{$path[0]};
				}
				return \@path;
			}
			push @queue, $parent_id;
		}
	}
	return;
}

=head2 find_redundant_parents ($taxonomy_ref)

Return the list of unnecessary parents of the taxonomy loaded with load_taxonomy().

Each item has: file, entry (canonical id), name (entry first line), parent (the unnecessary parent line hash)
implied_by (the other parent line of the entry) and path (canonical ids from implied_by to parent).

A parent is not reported if both parents are ancestors of each other (cycle).

=cut

sub find_redundant_parents ($taxonomy_ref) {
	my $direct_parents_ref = $taxonomy_ref->{direct_parents};
	my @redundant = ();
	foreach my $entry (@{$taxonomy_ref->{entries}}) {
		my @parents = grep {(defined $_->{canon_id}) and ($_->{canon_id} ne $entry->{canon_id})} @{$entry->{parents}};
		foreach my $i (0 .. $#parents) {
			my $parent = $parents[$i];
			foreach my $j (0 .. $#parents) {
				next if $i == $j;
				my $other = $parents[$j];
				my $path;
				if ($other->{canon_id} eq $parent->{canon_id}) {
					# same parent listed twice: keep the first one
					next if $j > $i;
					$path = [$parent->{canon_id}];
				}
				else {
					$path = find_path($direct_parents_ref, $other->{canon_id}, $parent->{canon_id});
					next if not defined $path;
					# cycle: do not choose
					next if defined find_path($direct_parents_ref, $parent->{canon_id}, $other->{canon_id});
				}
				push @redundant,
					{
					file => $entry->{file},
					entry => $entry->{canon_id},
					name => $entry->{name},
					start_line => $entry->{start_line},
					parent => $parent,
					implied_by => $other,
					path => $path,
					};
				last;
			}
		}
	}
	return \@redundant;
}

=head2 remove_lines (\@raw_lines, \%line_nums)

Return the raw lines, except the lines whose number (starting at 1) is in %line_nums.

=cut

sub remove_lines ($raw_lines_ref, $line_nums_ref) {
	my $line_num = 0;
	return [grep {$line_num++; not $line_nums_ref->{$line_num}} @$raw_lines_ref];
}

=head2 remove_redundant_parents ($taxonomy_ref, $redundant_ref)

Rewrite the taxonomy files without the unnecessary parent lines.
All other lines are kept byte for byte.

=cut

sub remove_redundant_parents ($taxonomy_ref, $redundant_ref) {
	my %lines_to_remove = ();    # file -> line_num -> 1
	foreach my $redundant (@$redundant_ref) {
		$lines_to_remove{$redundant->{file}}{$redundant->{parent}{line_num}} = 1;
	}
	foreach my $file (sort keys %lines_to_remove) {
		my $lines_ref = remove_lines($taxonomy_ref->{lines}{$file}, $lines_to_remove{$file});
		open(my $out, ">:raw", $file) or die("Cannot write $file: $!\n");
		print $out @$lines_ref;
		close($out) or die("Cannot write $file: $!\n");
	}
	return;
}

# text report of unnecessary parents and unknown parents
sub format_report ($redundant_ref, $unknown_ref) {
	my $report = "";
	foreach my $redundant (@$redundant_ref) {
		my $parent = $redundant->{parent};
		my $implied_by = $redundant->{implied_by};
		my $path = join(" > ", @{$redundant->{path}});
		my $reason
			= (@{$redundant->{path}} == 1)
			? "same entry as"
			: "already implied by";
		$report
			.= "$redundant->{file}:$parent->{line_num}: $redundant->{entry} ($redundant->{name})\n"
			. "\tunnecessary: $parent->{line}\n"
			. "\t$reason: $implied_by->{line} (line $implied_by->{line_num})"
			. ((@{$redundant->{path}} > 1) ? " - $path" : "") . "\n";
	}
	foreach my $unknown (@$unknown_ref) {
		$report .= "$unknown->{file}:$unknown->{line_num}: $unknown->{entry}\n"
			. "\tunknown parent (ignored): $unknown->{line}\n";
	}
	return $report;
}

# run the program only if called directly
unless (caller) {

	my $usage = <<TXT
Find unnecessary parents in taxonomies: parents that are already ancestors of another parent of the same entry,
or that are listed twice.

usage: $0 [--fix] [--quiet] file [file ...]

All files are loaded together as a single taxonomy, like the build does for taxonomies made of several files,
e.g. for the food ingredients taxonomy:
$0 taxonomies/additives_classes.txt taxonomies/additives.txt taxonomies/minerals.txt taxonomies/vitamins.txt \\
	taxonomies/amino_acids.txt taxonomies/nucleotides.txt taxonomies/other_nutritional_substances.txt \\
	taxonomies/food/ingredients.txt

--fix: remove unnecessary parent lines from the files (all other lines are kept as they are)
--quiet: only print counts
TXT
		;
	my $fix;
	my $quiet;
	GetOptions("fix" => \$fix, "quiet" => \$quiet) or die("Error in command line arguments.\n\n" . $usage);
	@ARGV or die($usage);

	binmode(STDOUT, ":encoding(UTF-8)");
	binmode(STDERR, ":encoding(UTF-8)");

	my $taxonomy_ref = load_taxonomy(\@ARGV);
	my $redundant_ref = find_redundant_parents($taxonomy_ref);
	my $unknown_ref = $taxonomy_ref->{unknown_parents};

	print format_report($redundant_ref, $unknown_ref) unless $quiet;

	my %counts = ();
	$counts{$_->{file}}++ foreach @$redundant_ref;
	foreach my $file (@ARGV) {
		print "$file: " . ($counts{$file} // 0) . " unnecessary parents\n";
	}
	print scalar(@$unknown_ref) . " unknown parents\n" if @$unknown_ref;

	if ($fix) {
		remove_redundant_parents($taxonomy_ref, $redundant_ref);
		print "Removed " . scalar(@$redundant_ref) . " parent lines\n";
	}
}

1;
