use ProductOpener::PerlStandards;
use utf8;

use ProductOpener::Paths qw/%BASE_DIRS/;
use ProductOpener::Products qw/get_source_for_site_and_org product_path_from_id retrieve_product store_product/;
use ProductOpener::Store qw/retrieve_object/;
use ProductOpener::ProductsTags qw/generate_field_tags_from_all_sources set_field_input_tags_for_source/;

use Getopt::Long;

# The 2026 scanbot run added countries to products with add_tags_to_field(), which does not work
# with the tags schema 1004: countries_tags was replaced with only the added countries, the added countries
# were not added to tags_sources, and old fields (countries, countries_hierarchy, countries_lc) were left in the product.
#
# This script reads the products CSV file generated by scanbot (e.g. /mnt/off/data/scanbot.2026/scanbot.2026.products.csv)
# and for each product with added countries:
# - removes the old fields and regenerates countries_tags from tags_sources (restoring the countries before scanbot)
# - adds back the countries of the revision before the scanbot edit: apps that edit countries start from countries_tags
#   and write the whole list back, so an edit made since scanbot may have removed them from the sources
# - adds the countries added by scanbot to the default source, if they are not already there
#   (also for products edited since scanbot: the edit may have removed the added countries without the user noticing)
# Products are saved with a specific user id, so that the repair can be told apart from a scanbot run,
# and only if something changed, so the script can be run again safely.
#
# Usage: 2026_10_fix_countries_added_by_scanbot.pl [--pretend] scanbot.2026.products.csv > report.tsv

my $pretend = 0;
GetOptions("pretend" => \$pretend) or die("Usage: $0 [--pretend] scanbot.products.csv\n");

my $csv_file = $ARGV[0] or die("Usage: $0 [--pretend] scanbot.products.csv\n");

binmode(STDOUT, ":encoding(UTF-8)");

my $source = get_source_for_site_and_org();
my $user_id = "fix-scanbot-countries-2026";
my %stats = ();

print join("\t",
	"code", "status", "last_editor", "countries_before", "countries_after",
	"added_back_scanbot_countries",
	"added_back_countries_before_scanbot",
	"rev_before_scanbot") . "\n";

open(my $in, "<:encoding(UTF-8)", $csv_file) or die("Cannot read $csv_file: $!\n");
while (my $line = <$in>) {
	chomp($line);
	# code, scans_n, unique_scans_n, found, source, added countries + '"' + countries list
	my ($code, $scans_n, $unique_scans_n, $found, $data_source, $rest) = split(/\t/, $line, 6);
	next if ((not defined $rest) or ($found ne "FOUND"));
	# Skip bogus codes (product "0" gets scans from apps that send it when the barcode is not read)
	next if ($code =~ /^0*$/);
	my ($added_countries) = split(/"/, $rest);
	next if ((not defined $added_countries) or ($added_countries eq ""));

	$stats{products_with_added_countries}++;

	my $product_ref = retrieve_product($code);
	if (not defined $product_ref) {
		$stats{not_found}++;
		print join("\t", $code, "not_found") . "\n";
		next;
	}

	my $last_editor = $product_ref->{last_editor} // "";
	my $had_old_fields = grep {exists $product_ref->{$_}} qw(countries countries_hierarchy countries_lc);
	my $countries_before = join(",", @{$product_ref->{countries_tags} // []});

	# Restore the countries from the sources
	delete @{$product_ref}{qw(countries countries_hierarchy countries_lc countries_beforescanbot)};
	generate_field_tags_from_all_sources($product_ref, "countries");

	# Countries of the revision before the scanbot edit (the scanbot comment starts with "product code")
	my $rev_before_scanbot = "";
	my @countries_before_scanbot = ();
	my $changes_ref = retrieve_object("$BASE_DIRS{PRODUCTS}/" . product_path_from_id($code) . "/changes") // [];
	foreach my $change_ref (reverse @$changes_ref) {
		if (    (($change_ref->{userid} // "") eq "scanbot")
			and (($change_ref->{comment} // "") =~ /^product code /)
			and (($change_ref->{rev} // 0) > 1))
		{
			$rev_before_scanbot = $change_ref->{rev} - 1;
			my $previous_product_ref = retrieve_product($code, 1, $rev_before_scanbot);
			if (defined $previous_product_ref) {
				@countries_before_scanbot = grep {$_ ne "en:world"} @{$previous_product_ref->{countries_tags} // []};
			}
			last;
		}
	}

	# Add the countries before scanbot and the countries added by scanbot that are not in the sources
	my %existing = map {$_ => 1} @{$product_ref->{countries_tags}};
	my @missing_before_scanbot = grep {not $existing{$_}} @countries_before_scanbot;
	$existing{$_} = 1 for @missing_before_scanbot;
	my @missing = grep {not $existing{$_}} split(/,/, $added_countries);
	foreach my $country (@missing_before_scanbot, @missing) {
		set_field_input_tags_for_source($product_ref, "en", "countries", $source, $country, 1);
	}

	my $countries_after = join(",", @{$product_ref->{countries_tags}});

	my $status = "ok";
	if (   $had_old_fields
		or (scalar @missing)
		or (scalar @missing_before_scanbot)
		or ($countries_after ne $countries_before))
	{
		$status = ($last_editor eq "scanbot") ? "fixed" : "fixed_edited_since";
		if (not $pretend) {
			store_product($user_id, $product_ref,
				"restore countries replaced by scanbot 2026 (tags refactor bug), and add the countries from scans");
		}
	}

	$stats{$status}++;
	print join("\t",
		$code, $status, $last_editor, $countries_before, $countries_after,
		join(",", @missing),
		join(",", @missing_before_scanbot),
		$rev_before_scanbot) . "\n";
}
close($in);

print STDERR ($pretend ? "PRETEND - no product was saved\n" : "");
print STDERR "$_: $stats{$_}\n" for sort keys %stats;
