#!/usr/bin/env python3
"""
Summarize JUnit XML test results for GitHub Actions CI and local runs.

Features:
- Parse JUnit XML test output generated by yath (Test2::Harness)
- Print an enjoyable, colorized summary to console with emojis/icons
- Highlight failed test files, specific test cases, and error messages
- When running in GitHub Actions:
  - Generate GitHub workflow error annotations (::error::)
  - Append a Markdown report to $GITHUB_STEP_SUMMARY with collapsible details
"""

import argparse
import os
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Dict, List, Optional, Any

# ANSI Colors
RESET = "\033[0m"
BOLD = "\033[1m"
DIM = "\033[2m"
RED = "\033[1;31m"
GREEN = "\033[1;32m"
YELLOW = "\033[1;33m"
BLUE = "\033[1;34m"
MAGENTA = "\033[1;35m"
CYAN = "\033[1;36m"
WHITE = "\033[1;37m"


class TestCaseResult:
    def __init__(self, name: str, classname: str, time: float, status: str, message: str = "", text: str = ""):
        self.name = name
        self.classname = classname
        self.time = time
        self.status = status  # 'passed', 'failed', 'error', 'skipped'
        self.message = message
        self.text = text


class TestSummary:
    def __init__(self, test_type: str = "Test", group: Optional[str] = None):
        self.test_type = test_type.capitalize()
        self.group = group
        self.total = 0
        self.passed = 0
        self.failed = 0
        self.errors = 0
        self.skipped = 0
        self.duration = 0.0
        self.cases: List[TestCaseResult] = []

    @property
    def title(self) -> str:
        group_str = f" Group {self.group}" if self.group else ""
        return f"{self.test_type} Tests{group_str}"


def parse_junit_xml(xml_file: Path) -> List[TestCaseResult]:
    """Parse a single JUnit XML file and return test cases."""
    cases = []
    try:
        tree = ET.parse(xml_file)
        root = tree.getroot()
    except Exception as e:
        print(f"{YELLOW}⚠️  Warning: Unable to parse {xml_file}: {e}{RESET}")
        return cases

    for testcase in root.findall(".//testcase"):
        name = testcase.get("name", "Unknown test")
        classname = testcase.get("classname", "")
        time_str = testcase.get("time", "0.0")
        try:
            time_val = float(time_str)
        except ValueError:
            time_val = 0.0

        status = "passed"
        message = ""
        text = ""

        # Check for failures
        failure = testcase.find("failure")
        if failure is not None:
            status = "failed"
            message = failure.get("message", "")
            text = (failure.text or "").strip()

        # Check for errors
        error = testcase.find("error")
        if error is not None:
            status = "error"
            message = error.get("message", "")
            text = (error.text or "").strip()

        # Check for skipped
        skipped = testcase.find("skipped")
        if skipped is not None:
            status = "skipped"
            message = skipped.get("message", "")

        cases.append(TestCaseResult(
            name=name,
            classname=classname,
            time=time_val,
            status=status,
            message=message,
            text=text
        ))

    return cases


def build_summary(junit_dir: Path, test_type: str, group: Optional[str]) -> TestSummary:
    summary = TestSummary(test_type=test_type, group=group)
    if not junit_dir.exists():
        return summary

    for xml_file in sorted(junit_dir.glob("*.xml")):
        cases = parse_junit_xml(xml_file)
        for c in cases:
            summary.cases.append(c)
            summary.total += 1
            summary.duration += c.time
            if c.status == "passed":
                summary.passed += 1
            elif c.status == "failed":
                summary.failed += 1
            elif c.status == "error":
                summary.errors += 1
            elif c.status == "skipped":
                summary.skipped += 1

    return summary


def print_console_summary(summary: TestSummary):
    """Print an eye-catching, informative summary to standard output."""
    border = "═" * 68
    divider = "─" * 68

    print(f"\n{CYAN}{BOLD}{border}{RESET}")
    print(f"{CYAN}{BOLD}📊 {summary.title} Execution Summary{RESET}")
    print(f"{CYAN}{BOLD}{border}{RESET}")

    total_failures = summary.failed + summary.errors

    # Overall stats bar
    status_icon = "✅" if total_failures == 0 and summary.total > 0 else ("❌" if total_failures > 0 else "⚠️")
    print(f" {status_icon} Total: {BOLD}{summary.total}{RESET}  |  "
          f"{GREEN}Passed: {summary.passed} ✅{RESET}  |  "
          f"{RED}Failed: {summary.failed} ❌{RESET}  |  "
          f"{YELLOW}Errors: {summary.errors} ⚠️{RESET}  |  "
          f"Duration: {BOLD}{summary.duration:.1f}s ⏱️{RESET}")
    print(f"{CYAN}{divider}{RESET}")

    # Detail failures
    failed_cases = [c for c in summary.cases if c.status in ("failed", "error")]
    if failed_cases:
        print(f"\n{RED}{BOLD}🚨 FAILED TESTS ({len(failed_cases)}):{RESET}")
        for i, c in enumerate(failed_cases, 1):
            file_info = f" ({c.classname})" if c.classname else ""
            print(f"\n  {RED}{BOLD}{i}. ❌ {c.name}{file_info}{RESET}  {DIM}[{c.time:.2f}s]{RESET}")
            if c.message:
                print(f"     {YELLOW}Message:{RESET} {c.message}")
            if c.text:
                # Print first few lines of text/trace
                lines = c.text.splitlines()
                preview = lines[:8]
                for l in preview:
                    print(f"     {DIM}│ {l}{RESET}")
                if len(lines) > 8:
                    print(f"     {DIM}│ ... ({len(lines) - 8} more lines omitted){RESET}")
        print(f"\n{RED}{BOLD}{border}{RESET}\n")
    elif summary.total > 0:
        print(f"\n{GREEN}{BOLD}✨ All {summary.total} tests completed successfully! 🎉{RESET}\n")
    else:
        print(f"\n{YELLOW}ℹ️  No test results found in target directory.{RESET}\n")


def write_github_summary(summary: TestSummary):
    """Append a rich markdown summary to $GITHUB_STEP_SUMMARY if available."""
    summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
    if not summary_path:
        return

    total_failures = summary.failed + summary.errors
    badge_status = "PASSED" if total_failures == 0 and summary.total > 0 else ("FAILED" if total_failures > 0 else "EMPTY")
    badge_color = "success" if badge_status == "PASSED" else "critical"

    lines = [
        f"### 📊 {summary.title} Results",
        "",
        f"| Metric | Value |",
        f"| :--- | :---: |",
        f"| **Status** | **{badge_status}** {'✅' if badge_status == 'PASSED' else '❌'} |",
        f"| **Total Tests** | {summary.total} |",
        f"| **Passed** | {summary.passed} ✅ |",
        f"| **Failed** | {summary.failed} ❌ |",
        f"| **Errors** | {summary.errors} ⚠️ |",
        f"| **Skipped** | {summary.skipped} ⏭️ |",
        f"| **Total Duration** | {summary.duration:.1f}s ⏱️ |",
        ""
    ]

    failed_cases = [c for c in summary.cases if c.status in ("failed", "error")]
    if failed_cases:
        lines.append(f"<details open>")
        lines.append(f"<summary><b>❌ Failed Tests ({len(failed_cases)})</b> — Click to collapse</summary>\n")
        lines.append("| # | Test File / Class | Test Case | Duration | Message |")
        lines.append("| :-: | :--- | :--- | :-: | :--- |")
        for i, c in enumerate(failed_cases, 1):
            file_name = c.classname or "N/A"
            msg = (c.message or "Check log").replace("\n", " ")
            lines.append(f"| {i} | `{file_name}` | **`{c.name}`** | {c.time:.2f}s | {msg} |")
        lines.append("\n</details>\n")

    # Passed tests collapsible
    passed_cases = [c for c in summary.cases if c.status == "passed"]
    if passed_cases:
        lines.append(f"<details>")
        lines.append(f"<summary><b>✅ Passed Tests ({len(passed_cases)})</b> — Click to expand</summary>\n")
        lines.append("| Test Name | Duration |")
        lines.append("| :--- | :-: |")
        for c in passed_cases:
            lines.append(f"| `{c.name}` | {c.time:.2f}s |")
        lines.append("\n</details>\n")

    try:
        with open(summary_path, "a", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
    except Exception as e:
        print(f"{YELLOW}⚠️  Warning: Unable to write to GITHUB_STEP_SUMMARY: {e}{RESET}")


def emit_github_annotations(summary: TestSummary):
    """Emit ::error and ::warning workflow commands for failed tests."""
    for c in summary.cases:
        if c.status in ("failed", "error"):
            file_param = f"file={c.classname}," if c.classname else ""
            msg = (c.message or f"Test '{c.name}' failed").replace("\n", " ")
            print(f"::error {file_param}title=Test Failed: {c.name}::{msg}")


def main():
    parser = argparse.ArgumentParser(description="Summarize JUnit XML test results with colors and icons")
    parser.add_argument("--junit-dir", required=True, type=Path, help="Directory containing JUnit XML outputs")
    parser.add_argument("--type", default="Test", help="Test type label (e.g. Unit, Integration)")
    parser.add_argument("--group", default=None, help="Optional group number")
    parser.add_argument("--fail-on-error", action="store_true", help="Exit with code 1 if any tests failed")

    args = parser.parse_args()

    summary = build_summary(args.junit_dir, args.type, args.group)
    print_console_summary(summary)

    if os.environ.get("GITHUB_ACTIONS"):
        write_github_summary(summary)
        emit_github_annotations(summary)

    if args.fail_on_error and (summary.failed > 0 or summary.errors > 0):
        sys.exit(1)


if __name__ == "__main__":
    main()
